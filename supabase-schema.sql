-- Portfolia: database schema for Supabase
-- Run this in Supabase Dashboard > SQL Editor.
-- This public demo schema allows anonymous CRUD so an instructor can test the project.
-- IMPORTANT: This is suitable only for a non-sensitive class demo. Anyone with the site
-- can read, edit, or delete records. For production, add Supabase Auth and owner-based RLS.

create table if not exists public.portfolios (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  contact_number text,
  address text,
  profile_picture text,
  about_me text not null,
  education text,
  skills text,
  projects text,
  experience text,
  social_links text,
  template text not null default 'simple'
    check (template in ('simple', 'modern', 'creative')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.portfolios enable row level security;

drop policy if exists "Public can read portfolios" on public.portfolios;
create policy "Public can read portfolios"
on public.portfolios for select to anon, authenticated
using (true);

drop policy if exists "Public can create portfolios" on public.portfolios;
create policy "Public can create portfolios"
on public.portfolios for insert to anon, authenticated
with check (true);

drop policy if exists "Public can update portfolios" on public.portfolios;
create policy "Public can update portfolios"
on public.portfolios for update to anon, authenticated
using (true) with check (true);

drop policy if exists "Public can delete portfolios" on public.portfolios;
create policy "Public can delete portfolios"
on public.portfolios for delete to anon, authenticated
using (true);

create or replace function public.set_portfolio_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_portfolio_updated_at on public.portfolios;
create trigger set_portfolio_updated_at
before update on public.portfolios
for each row execute function public.set_portfolio_updated_at();

-- If your Supabase project requires explicit Data API grants, run:
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.portfolios to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
